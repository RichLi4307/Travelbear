# 场景转换演示默认走的路线（目标名）
DEMO_SEQUENCE: List[str] = ["外白渡桥", "和平饭店", "陆家嘴天际线"]

_BY_NAME = {name: (short, text) for name, short, text in TARGETS}


def names() -> List[str]:
    """全部讲解目标名，按游览顺序。"""
    return [name for name, _, _ in TARGETS]


def short_of(name: str) -> str:
    """一句话定位。"""
    return _BY_NAME[name][0]


def text_of(name: str) -> str:
    """讲解文案。"""
    return _BY_NAME[name][1]


def tuple_of(name: str) -> Tuple[str, str, str]:
    return name, *_BY_NAME[name]


def in_order(seq: List[str]) -> List[Tuple[str, str, str]]:
    return [tuple_of(n) for n in seq]
